CREATE PROCEDURE [dbo].[USP_ROI_GETITEMRATE]

AS
BEGIN

	SELECT IR.ItemRateID,
	IR.ItemID,
	IR.UnitID,
	IR.PRate,
	IR.SRate,
	IM.ITId,
	IM.ITName,
	IR.ValidFrom AS Validfroms
	FROM DBO.ROI_ITEMRATE IR
	INNER JOIN DBO.ROI_ITEMMain IM ON IM.ITId = IR.ItemID
END






GO
